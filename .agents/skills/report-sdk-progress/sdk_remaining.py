#!/usr/bin/env python3
"""Report how much library (SDK, libc, runtime, SN stub) code and data is still unsplit.

Measures by address coverage, not by counting function symbols, so code that dtk only knows as
`lbl_` labels (no `type:function` symbol) is counted too. Needs a finished build (`ninja`). Checks:
  - build/<version>/main.dol against config/<version>/build.sha1: nothing below is trustworthy otherwise;
  - .text of both library clusters (ranges and per-library labels come from tools/sdk_scout.py);
  - the whole .init section (boot/runtime code: __start and friends);
  - data: every library data run in DATA_RANGES (tools/sdk_scout.py, both clusters, all sections), split vs
    unsplit. An unsplit byte a dtk auto_ unit emits is library data no unit owns (queued if a data row in
    docs/sdk_queue.tsv covers it); one no auto_ unit emits is alignment padding the linker inserts;
  - boundary: no library code reaches into an auto_ unit, through a relocation in dtk's extracted objects
    or an r13 access (sda2_via_r13 bakes those relocations away), outside EXPECTED_OUTSIDE;
  - build/<version>/report.json: registered library units that don't fully match.

Usage (from repo root): sdk_remaining.py [--version GVLE69] [--lo 0x.. --hi 0x..] [--list]
"""
import argparse
import bisect
import collections
import hashlib
import json
import re
import struct
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, "tools")
import sdk_scout  # noqa: E402  (RANGES and LIBS are the single source of truth)

# The only addresses outside every library unit that library code may reference: the game's entry point
# and the linker-built tables crt0 and the GCC runtime walk. Anything else the boundary check prints is a
# library object still emitted by a dtk auto_ unit, or a range in tools/sdk_scout.py that is wrong.
EXPECTED_OUTSIDE = {
    0x8002A124: "main (game code), called by __start",
    0x804825A0: "GCC's constructor list (all of .rodata), walked by __do_global_ctors",
    0x804DCD84: "the empty .ctors list, walked by fn_801813F4",
    0x804DCD8C: "the empty .dtors list, walked by fn_80181448",
    0x8050F760: ".bss start, zeroed by __start",
    0x8066B4E0: ".sdata start, the end of the .bss __start zeroes",
    0x8066CF20: ".sbss start, zeroed by __start",
}

ap = argparse.ArgumentParser()
ap.add_argument("--version", default="GVLE69")
ap.add_argument("--lo", type=lambda x: int(x, 0), default=None)
ap.add_argument("--hi", type=lambda x: int(x, 0), default=None)
ap.add_argument("--list", action="store_true", help="also list every gap and every unsplit fn_ function")
args = ap.parse_args()
CLUSTERS = [(lo, hi) for lo, hi, _ in sdk_scout.RANGES]
if args.lo is not None or args.hi is not None:
    CLUSTERS = [(args.lo if args.lo is not None else CLUSTERS[0][0], args.hi if args.hi is not None else CLUSTERS[0][1])]

cfg = Path("config") / args.version
build = Path("build") / args.version
ANON = re.compile(r"^(fn|lbl|gap|pad)_[0-9A-F]{8}")

# --- build ---------------------------------------------------------------------------------------
if not (build / "config.json").exists():
    sys.exit(f"{build / 'config.json'} missing: run ninja first")
want, path = (cfg / "build.sha1").read_text().split()
got = hashlib.sha1(Path(path).read_bytes()).hexdigest() if Path(path).exists() else "missing"
print(f"{path}: {'OK' if got == want else f'MISMATCH ({got}): stop, the report below is not trustworthy'}\n")
# dtk's auto_ units: the gaps between our splits that dtk fills from generated asm, named auto_<n>_<ADDR>_<sec>
build_units = json.loads((build / "config.json").read_text())["units"]
auto_units = []
for u in build_units:
    if u.get("autogenerated"):
        a = int(u["name"].split("_")[2], 16)
        auto_units.append((a, a + u.get("code_size", 0) + u.get("data_size", 0), u["name"]))

# splits: section -> [(start, end, unit)]
splits, cur = collections.defaultdict(list), None
for line in (cfg / "splits.txt").read_text().splitlines():
    m = re.match(r"^(\S+):$", line)
    if m:
        cur = m[1]
        continue
    m = re.search(r"^\s+(\.\S+)\s+start:0x([0-9A-F]+) end:0x([0-9A-F]+)", line)
    if m and cur:
        splits[m[1]].append((int(m[2], 16), int(m[3], 16), cur))
for v in splits.values():
    v.sort()

# symbols: (addr, name, section, type, size)
syms = []
for line in (cfg / "symbols.txt").read_text().splitlines():
    m = re.match(r"(\S+) = (\.\S+):0x([0-9A-F]+); // type:(\w+)(?:.*? size:0x([0-9A-F]+))?", line)
    if m:
        syms.append((int(m[3], 16), m[1], m[2], m[4], int(m[5] or "0", 16)))
syms.sort()


def uncovered(intervals, lo, hi):
    """Address ranges in [lo, hi) that none of the (start, end) intervals cover."""
    out, pos = [], lo
    for a, b in sorted(intervals):
        if b <= lo or a >= hi:
            continue
        if a > pos:
            out.append((pos, a))
        pos = max(pos, b)
    if pos < hi:
        out.append((pos, hi))
    return out


def gaps(section, lo, hi):
    """Address ranges in [lo, hi) that no split of `section` covers."""
    return uncovered([(a, b) for a, b, _ in splits.get(section, [])], lo, hi)


def by_lib(lo, hi):
    """Split [lo, hi) at sdk_scout.LIBS boundaries: [(lo, hi, lib)]."""
    cuts = sorted({lo, hi} | {x for s, e, _, _ in sdk_scout.LIBS for x in (s, e) if lo < x < hi})
    return [(a, b, sdk_scout.lib_of(a)) for a, b in zip(cuts, cuts[1:])]


def in_gaps(gs, a):
    return any(lo <= a < hi for lo, hi in gs)


def func_extents(section):
    return [(a, a + s) for a, _, sec, t, s in syms if sec == section and t == "function" and s]


def no_func_runs(section, lo, hi):
    """Runs in [lo, hi) that no sized function symbol covers (code dtk only knows as labels)."""
    out, pos = [], lo
    for a, b in func_extents(section):
        if b <= pos or a >= hi:
            continue
        if a > pos:
            out.append((pos, a))
        pos = max(pos, b)
    if pos < hi:
        out.append((pos, hi))
    return out


# --- .text of the library clusters -------------------------------------------------------------
text_gaps = [g for lo, hi in CLUSTERS for g in gaps(".text", lo, hi)]
funcs = [s for s in syms if s[2] == ".text" and s[3] == "function" and any(lo <= s[0] < hi for lo, hi in CLUSTERS)]
unsplit = [s for s in funcs if in_gaps(text_gaps, s[0])]
named = [s for s in unsplit if not ANON.match(s[1])]
anon = [s for s in unsplit if ANON.match(s[1])]
inside_func = lambda a: any(x <= a < y for x, y in func_extents(".text"))
named_labels = [s for s in syms if s[2] == ".text" and s[3] == "label" and not ANON.match(s[1])
                and in_gaps(text_gaps, s[0]) and not inside_func(s[0])]  # e.g. __cvt_fp2unsigned
lib_bytes = collections.Counter()
for a, b in text_gaps:
    for x, y, lib in by_lib(a, b):
        lib_bytes[lib] += y - x
label_only = [r for a, b in text_gaps for r in no_func_runs(".text", a, b) if r[1] - r[0] >= 0x40]

print(".text, library clusters (by address; lbl_-only code included)")
for lo, hi in CLUSTERS:
    g = [x for x in text_gaps if lo <= x[0] < hi]
    n = sum(1 for s in funcs if lo <= s[0] < hi)
    u = sum(1 for s in unsplit if lo <= s[0] < hi)
    print(f"  {lo:#x}-{hi:#x}: {sum(b - a for a, b in g)} of {hi - lo} bytes unsplit in {len(g)} gaps; "
          f"{u} of {n} function symbols unsplit")
print(f"  unsplit bytes by library: {dict(lib_bytes.most_common())}")
print(f"  unsplit function symbols: {len(unsplit)} ({len(named)} named, {len(anon)} anonymous fn_*)")
print(f"  code with no function symbol ({sum(b - a for a, b in label_only)} bytes in runs >= 0x40; needs function"
      " boundaries in symbols.txt before it can be split):")
for a, b in label_only:
    libs = ", ".join(sorted({lib for _, _, lib in by_lib(a, b)}))
    print(f"    {a:#x}-{b:#x}: {b - a} bytes [{libs}]")
print("  named but unsplit (functions, then named labels):")
for a, n, _, _, s in named:
    print(f"    {a:#x} {n} ({s:#x}) [{sdk_scout.lib_of(a)}]")
for a, n, *_ in named_labels:
    print(f"    {a:#x} {n} (label) [{sdk_scout.lib_of(a)}]")

# --- .init ---------------------------------------------------------------------------------------
dol = (Path("orig") / args.version / "sys" / "main.dol").read_bytes()
offs, addrs, sizes = (struct.unpack(">18I", dol[o:o + 0x48]) for o in (0, 0x48, 0x90))


def dol_read(a, n):
    """n bytes at address a in the original main.dol, or None outside its sections (.bss/.sbss)."""
    for off, lo, size in zip(offs, addrs, sizes):
        if lo <= a and a + n <= lo + size:
            return dol[off + a - lo:off + a - lo + n]


init = (addrs[0], addrs[0] + sizes[0])  # text0 is .init
g = gaps(".init", *init)
init_unsplit = sum(b - a for a, b in g)
fs = [s for s in syms if s[2] == ".init" and s[3] == "function"]
print(f"\n.init {init[0]:#x}-{init[1]:#x} (boot/runtime): {sum(b - a for a, b in g)} of {init[1] - init[0]} "
      f"bytes unsplit; functions: {', '.join(n for _, n, *_ in fs)}")

# --- data ------------------------------------------------------------------------------------------
# Measured against the mapped runs (sdk_scout.DATA_RANGES), not against the span of existing splits, so game
# data between the clusters is excluded and unsplit library data before the first split is included.
# unsplit = padding (no auto_ unit emits it, so the linker inserted it between two of our units: alignment,
# while main.dol matches) + unclaimed (a dtk auto_ unit emits it from generated asm: library data no unit owns,
# or alignment the next split doesn't declare). Unclaimed bytes are queued (an open/stalled data row covers
# them) or NOT QUEUED (the queue is stale or a run is mis-mapped). Whether a symbol covers a byte says nothing
# either way: dtk keeps stale labels on padding and has none for unreferenced data.
DATA_SECS = (".rodata", ".rodata.1", ".data", ".bss", ".sdata", ".sbss", ".sdata2")
qrows = []  # (section, start, end, library, status) of every data row in the queue
queue = Path("docs/sdk_queue.tsv")
if queue.exists():
    for line in queue.read_text().splitlines()[1:]:
        c = line.split("\t")
        m = re.match(r"data (\.\S+):", c[5]) if len(c) == 7 else None
        if m:
            a = int(c[0], 16)
            qrows.append((m[1], a, a + int(c[1], 16), c[3], c[6]))


def covered(intervals, lo, hi):
    """Bytes of [lo, hi) that the (start, end) intervals cover."""
    return (hi - lo) - sum(b - a for a, b in uncovered(intervals, lo, hi))


def align_hint(a, b):
    """N if [a, b) is all zero and ends exactly where an N-byte-aligned object would start (N > 8, dtk's default)."""
    data = dol_read(a, b - a)
    if data is None or not any(data):
        return next((n for n in (16, 32, 64) if b % n == 0 and -(-a // n) * n == b), None)


lib_units = {u for a, b, u in splits.get(".text", []) if any(lo <= a < hi for lo, hi in CLUSTERS)}
lib_units |= {u for v in splits.values() for *_, u in v if u.startswith(("Dolphin/", "Runtime.PPCEABI.H/", "SN/"))}
print("\nData: library data runs (DATA_RANGES in tools/sdk_scout.py; padding = linker-inserted,"
      " queued = open/stalled data rows)")
tot = collections.Counter()
lib_data = collections.Counter()
unqueued_gaps = []
for sec, lo, hi, cl in sorted(sdk_scout.DATA_RANGES, key=lambda r: (r[3], DATA_SECS.index(r[0]), r[1])):
    split_n = covered([(a, b) for a, b, _ in splits.get(sec, [])], lo, hi)
    open_rows = [r for r in qrows if r[0] == sec and r[4] in ("open", "stalled") and r[1] < hi and r[2] > lo]
    rows = [(x, y) for _, x, y, _, _ in open_rows]
    queued = pad = unq = 0
    for a, b in gaps(sec, lo, hi):
        asm = [(max(x, a), min(y, b)) for x, y, _ in auto_units if x < b and y > a]
        pad += (b - a) - covered(asm, a, b)
        for x, y in asm:
            queued += covered(rows, x, y)
            for _, rx, ry, lib, _ in open_rows:
                lib_data[lib] += covered([(rx, ry)], x, y)
            for u, v in uncovered(rows, x, y):
                unq += v - u
                unqueued_gaps.append((sec, u, v, b))
    tot.update(total=hi - lo, split=split_n, queued=queued, pad=pad, unqueued=unq)
    print(f"  cluster {cl} {sec:9} {lo:#x}-{hi:#x}: {hi - lo:6} bytes, split {split_n:6}, unsplit {hi - lo - split_n:6}"
          f" (queued {queued}, padding {pad}" + (f", NOT QUEUED {unq}" if unq else "") + ")")
    if args.list:
        for a, b in gaps(sec, lo, hi):
            asm = [n for x, y, n in auto_units if x < b and y > a]
            r = [f"{x:#x}+{y - x:#x}" for x, y in rows if x < b and y > a]
            what = f"{', '.join(asm)}, " + (f"rows {', '.join(r)}" if r else "no row") if asm else "linker padding"
            print(f"      gap {a:#x}-{b:#x} ({b - a} bytes): {what}")
unsplit_data = tot["queued"] + tot["unqueued"]
print(f"  total: {tot['total']} bytes of library data, {tot['split']} split, {tot['total'] - tot['split']} unsplit"
      f" ({tot['queued']} queued, {tot['unqueued']} not queued, {tot['pad']} linker padding)")
print(f"  unsplit (queued) bytes by library: {dict(lib_data.most_common())}")
next_unit = {(sec, a): u for sec, v in splits.items() for a, _, u in v}
for sec, a, b, end in unqueued_gaps:
    n = align_hint(a, b) if b == end else None
    if n:
        print(f"  NOT QUEUED: {sec} {a:#x}-{b:#x} ({b - a} bytes): zero, and ends exactly at the {n}-byte boundary"
              f" where {next_unit.get((sec, b), 'the next split')} starts. If that object is {n}-byte aligned,"
              f" declare it (align:{n} on the split, and in the source) so dtk drops the auto_ unit and the linker"
              " inserts the pad (docs/matching_notes.md); otherwise claim the bytes")
    else:
        print(f"  NOT QUEUED: {sec} {a:#x}-{b:#x} ({b - a} bytes): library data no unit owns. Claim it into the unit"
              " its position gives (\"Owners\" in docs/sdk_libraries.md) or add a data row -- first check that"
              " splits.txt/report.json don't already cover it through a nearby row (a stale 'matched' row can"
              " overclaim its size) and that the run isn't mis-mapped")
outside = [(sec, a, b, u) for sec in DATA_SECS for a, b, u in splits.get(sec, [])
           if u in lib_units and not any(s == sec and lo <= a and b <= hi for s, lo, hi, _ in sdk_scout.DATA_RANGES)]
for sec, a, b, u in outside:
    print(f"  library split outside every run: {u} {sec} {a:#x}-{b:#x} (fix DATA_RANGES or the split)")

# --- boundary ------------------------------------------------------------------------------------
# Library code may only reach outside the library units for EXPECTED_OUTSIDE. Anything else is a library object
# no unit owns yet, or a range in tools/sdk_scout.py that is wrong. Relocations come from the original objects
# dtk extracts; r13 accesses are scanned in the original code, because sda2_via_r13 bakes their relocations away.
lib_spans = sorted((a, b, u) for v in splits.values() for a, b, u in v if u in lib_units)
lib_starts = [a for a, _, _ in lib_spans]


def owner(t):
    """The library unit whose split holds address t, else the auto_ unit, else None."""
    i = bisect.bisect_right(lib_starts, t) - 1
    if i >= 0 and t < lib_spans[i][1]:
        return lib_spans[i][2]
    return next((n for x, y, n in auto_units if x <= t < y), None)


objs = {u["object"]: u["name"] for u in build_units}
nm = subprocess.run([str(Path("build/binutils/powerpc-eabi-nm")), "-A", *objs], capture_output=True, text=True).stdout
defined, wanted = {}, collections.defaultdict(set)
for line in nm.splitlines():
    f, rest = line.split(":", 1)
    p = rest.split()
    if p[0] == "U":
        wanted[p[1]].add(objs[f])
    elif len(p) == 3:
        defined.setdefault(p[2], objs[f])
addr_of = {n: a for a, n, *_ in syms}
name_at = {a: n for a, n, *_ in reversed(syms)}
reach = collections.defaultdict(lambda: [None, None, set()])  # address -> [name, owner, library users]
for name, users in wanted.items():
    d = defined.get(name)  # undefined everywhere: a linker-generated symbol such as _stack_addr
    if d and d not in lib_units and users & lib_units:
        r = reach[addr_of.get(name, -1)]
        r[0], r[1] = name, d
        r[2] |= users & lib_units
sda = json.loads((build / "sda_bake.json").read_text())["sda_base"]
for lo, hi in CLUSTERS + [init]:
    for a in range(lo, hi, 4):
        w = struct.unpack(">I", dol_read(a, 4))[0]
        if (w >> 26 == 14 or 32 <= w >> 26 <= 55) and (w >> 16) & 31 == 13:  # addi or a D-form load/store off r13
            t = (sda + ((w & 0xFFFF) ^ 0x8000) - 0x8000) & 0xFFFFFFFF
            o = owner(t)
            if o not in lib_units:
                r = reach[t]
                r[0], r[1] = r[0] or name_at.get(t, f"r13{t - sda:+#x}"), o or "no unit"
                r[2].add(owner(a) or f"{a:#x}")
unexpected = sorted((t, r) for t, r in reach.items() if t not in EXPECTED_OUTSIDE)
print(f"\nBoundary: addresses outside every library unit that library code reaches: {len(reach) - len(unexpected)}"
      f" expected (EXPECTED_OUTSIDE), {len(unexpected)} not")
for t, (name, o, users) in unexpected:
    more = f" (+{len(users) - 4} more)" if len(users) > 4 else ""
    print(f"  {t:#x} {name} in {o}, from {', '.join(sorted(users)[:4])}{more}")
if args.list:
    for t, (name, o, users) in sorted(reach.items()):
        if t in EXPECTED_OUTSIDE:
            print(f"  expected: {t:#x} {name} in {o}: {EXPECTED_OUTSIDE[t]}")

# --- registered units that don't fully match -------------------------------------------------------
report = Path("build") / args.version / "report.json"
if report.exists():
    bad = []
    for u in json.loads(report.read_text())["units"]:
        m, cats = u["measures"], u.get("metadata", {}).get("progress_categories", [])
        if "sdk" not in cats:
            continue
        code = (int(m.get("matched_code", 0)), int(m.get("total_code", 0)))
        data = (int(m.get("matched_data", 0)), int(m.get("total_data", 0)))
        if code[0] != code[1] or data[0] != data[1]:
            bad.append((u["name"].removeprefix("main/"), code, data))
    cat = next(c["measures"] for c in json.loads(report.read_text())["categories"] if c["id"] == "sdk")
    code_all = int(cat["total_code"]) + sum(b - a for a, b in text_gaps) + init_unsplit
    data_all = int(cat["total_data"]) + unsplit_data
    print(f"\nAll library code (registered + unsplit .text + unsplit .init): {cat['matched_code']} of {code_all} "
          f"bytes matched = {100 * int(cat['matched_code']) / code_all:.2f}% (progress says {cat['matched_code_percent']:.2f}%,"
          " registered units only)")
    print(f"All library data (registered + unsplit, padding excluded): {cat['matched_data']} of {data_all} bytes"
          f" matched = {100 * int(cat['matched_data']) / data_all:.2f}% (progress says {cat['matched_data_percent']:.2f}%,"
          " registered units only)")
    print(f"\nRegistered library units not fully matched (report.json): {len(bad)}")
    for n, c, dd in bad:
        what = [f"{k} {x}/{y}" for k, (x, y) in (("code", c), ("data", dd)) if x != y]
        print(f"  {n}: {', '.join(what)}")
else:
    print(f"\n({report} missing: run ninja first to list unmatched registered units)")

if args.list:
    print("\nAll .text gaps:")
    for a, b in text_gaps:
        print(f"  {a:#x}-{b:#x} ({b - a} bytes) [{', '.join(sorted({l for *_, l in by_lib(a, b)}))}]")
    print("\nAnonymous unsplit functions:")
    for a, n, _, _, s in anon:
        print(f"  {a:#x} {n} ({s:#x}) [{sdk_scout.lib_of(a)}]")
